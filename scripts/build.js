// Builds the package.
//
// 1. Generates src/package-info.ts from package.json so that the library can
//    report its own name and version (the User-Agent of the API requests). It can
//    not be a JSON import: those need different syntax in ES modules and CommonJS.
// 2. Compiles src/ twice with tsc: once as ES modules into dist/esm and once as
//    CommonJS into dist/cjs. Each output directory gets its own package.json
//    that pins the module format.
// 3. Points the default export of the CommonJS entry point at the exports object
//    itself, non-enumerable. Before the TypeScript build `require('@postalsys/email-ai-tools')`
//    was a plain object of named members with no default, and its enumerable keys stay
//    exactly those members; the ES module entry has a default export object for
//    `import emailAiTools from '@postalsys/email-ai-tools'`, which used to get module.exports.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsc = require.resolve('typescript/bin/tsc');

const ENTRY_POINT_SHIM = "Object.defineProperty(exports, 'default', { value: exports, enumerable: false, writable: true, configurable: true });\n";

function generatePackageInfo() {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    const source =
        [
            '// Generated by scripts/build.js from package.json. Do not edit by hand.',
            '',
            `export const name = ${JSON.stringify(pkg.name)};`,
            `export const version = ${JSON.stringify(pkg.version)};`
        ].join('\n') + '\n';
    writeIfChanged(path.join(root, 'src', 'package-info.ts'), source);
}

// Skips the write when the content is already there so that tsc caches stay warm
function writeIfChanged(target, source) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) {
        fs.writeFileSync(target, source);
    }
}

function runTsc(project, ...args) {
    const result = spawnSync(process.execPath, [tsc, '-p', project, ...args], { cwd: root, stdio: 'inherit' });
    if (result.status !== 0) {
        process.exit(result.status || 1);
    }
}

function build() {
    generatePackageInfo();
    fs.rmSync(path.join(root, 'dist'), { recursive: true, force: true });

    runTsc('tsconfig.esm.json');
    // The ES module compile has already type-checked the same sources
    runTsc('tsconfig.cjs.json', '--noCheck');

    fs.writeFileSync(path.join(root, 'dist', 'esm', 'package.json'), JSON.stringify({ type: 'module' }, null, 4) + '\n');
    fs.writeFileSync(path.join(root, 'dist', 'cjs', 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 4) + '\n');

    fs.appendFileSync(path.join(root, 'dist', 'cjs', 'index.js'), ENTRY_POINT_SHIM);
}

if (process.argv.includes('--generate-only')) {
    generatePackageInfo();
} else {
    build();
}
